DASHBOARD_LIST_Y = 184
DASHBOARD_LIST_HEIGHT = 510


def visible_events(root):
    paths = [root / "events/auto_qol_council_events.txt"]
    paths += sorted((root / "events").glob("auto_qol_council_assign_*_events.txt"))
    found = []
    for path in paths:
        text = path.read_text(encoding="utf-8-sig")
        cursor = 0
        while match := re.search(r"\bcountry_event\s*=\s*\{", text[cursor:]):
            start = cursor + match.start()
            opening = text.index("{", start)
            end = find_matching_brace(text, opening)
            if end < 0:
                raise ValueError(f"Unbalanced event: {path}")
            block = text[start:end + 1]
            if re.search(r"(?m)^\s*title\s*=", block):
                event_id = re.search(r"(?m)^\s*id\s*=\s*(\w+\.\d+)", block)[1]
                found.append((event_id, block))
            cursor = end + 1
    if not found:
        raise ValueError("No council workflow events found")
    ids = [event_id for event_id, _ in found]
    if len(set(ids)) != len(ids):
        raise ValueError("Duplicate source council event IDs")
    return found


def gui_id(event_id):
    stem, number = event_id.split(".")
    return stem.replace("auto_qol_council_", "auto_qol_council_gui_") + "." + number


def clone_events(root):
    source = visible_events(root)
    routes = {event_id: gui_id(event_id) for event_id, _ in source}
    output = ["# Generated by tools/build_council_gui.py; do not edit by hand.\n"]
    output += ["namespace = " + stem.replace("auto_qol_council_", "auto_qol_council_gui_") + "\n" for stem in STEMS]
    output.append('''namespace = auto_qol_council_gui
country_event = {
 id = auto_qol_council_gui.1
 hide_window = yes
 is_triggered_only = yes
 trigger = { is_ai = no }
 immediate = { country_event = { id = auto_qol_council_gui_menu.1 } }
}
''')
    for _, block in source:
        # Only event routing changes; localisation and saved leader targets retain
        # their original keys. Never do a global namespace string replacement.
        block = re.sub(r"\bid\s*=\s*(\w+\.\d+)", lambda m: "id = " + routes.get(m[1], m[1]), block)
        opening = block.index("{") + 1
        block = block[:opening] + '''
 diplomatic = yes
 custom_gui = "auto_qol_council_window"
 custom_gui_option = "auto_qol_council_option"
''' + block[opening:]
        # All clones are player-only, including direct console invocation.
        block = block[:block.rfind("}")] + "\n trigger = { is_ai = no }\n" + block[block.rfind("}"):]
        output.append(block + "\n")
    return "\n".join(output)


def dashboard_shell(prefix):
    gui = SHELL.replace("auto_qol_military_option", "auto_qol_council_option").replace("auto_qol_military_window", "auto_qol_council_window")
    gui = gui.replace("width = 290 height = 30", "width = 630 height = 34")
    gui = gui.replace("x = 290 y = 28", "x = 630 y = 32")
    # Preserve all native bindings, especially the required text/list scrollbars.
    gui = gui.replace('name = "alien_message"\n   font = "cg_16b"\n   position = { x = -10000 y = -10000 }\n   maxWidth = 465\n   maxHeight = 220',
                      'name = "alien_message"\n   font = "cg_16b"\n   position = { x = 22 y = 112 }\n   maxWidth = 300\n   maxHeight = 230')
    gui = gui.replace('name = "action_title" font = "malgun_goth_24" position = { x = -10000 y = -10000 }',
                      'name = "action_title" font = "malgun_goth_24" position = { x = 352 y = 116 } maxWidth = 630 maxHeight = 52')
    gui = gui.replace("x = 700 y = 630", f"x = 352 y = {DASHBOARD_LIST_Y}").replace("x = 300 y = 70", f"x = 650 y = {DASHBOARD_LIST_HEIGHT}")
    return gui.replace("auto_qol_council_option", prefix + "_option").replace("auto_qol_council_window", prefix + "_window")


