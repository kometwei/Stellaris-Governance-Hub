"""Archive generator for the superseded same-system experiment.

The on-demand organizer is built by build_scattered_fleet_organizer.py.
This generator no longer writes active game events.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NS = "auto_qol_reassembly"


def event(number, body):
    return f"country_event = {{\n id = {NS}.{number}\n is_triggered_only = yes\n trigger = {{ is_ai = no }}\n{body}\n}}\n"


def option(name, effects, trigger="", tooltip=""):
    return (f' option = {{\n  name = "{NS}.{name}"\n'
            + (f"  trigger = {{ {trigger} }}\n" if trigger else "")
            + (f'  custom_tooltip = "{NS}.{tooltip}"\n' if tooltip else "")
            + f"  hidden_effect = {{ {effects} }}\n }}\n")


def build():
    # Slot flags are cleared on EVERY page, so stale event targets cannot enable
    # an old button. Seen flags persist only for this browsing session.
    cleanup = "\n".join(f"remove_fleet_flag = {NS}_slot_{i}" for i in range(1, 7))
    reset = f"every_owned_fleet = {{ remove_fleet_flag = {NS}_seen {cleanup} }}"
    text = f"namespace = {NS}\n# Generated by tools/build_fleet_reassembly.py.\n"
    text += event(1, f"hide_window = yes\nimmediate = {{ {reset}\n country_event = {{ id = {NS}.2 }} }}")
    for number, kind in [(2, "target"), (3, "source")]:
        source = kind == "source"
        eligibility = "auto_qol_reassembly_source = yes" if source else "auto_qol_reassembly_target = yes"
        eligibility += f" NOT = {{ has_fleet_flag = {NS}_seen }}"
        immediate = f"every_owned_fleet = {{ {cleanup} }}\n"
        for i in range(1, 7):
            immediate += f"""
 ordered_owned_fleet = {{
  limit = {{ {eligibility} }}
  order_by = trigger:fleet_size
  position = 0
  set_fleet_flag = {NS}_seen
  set_fleet_flag = {NS}_slot_{i}
  save_event_target_as = {NS}_slot_{i}
 }}
"""
        body = f'title = "{NS}.{kind}.title"\ndesc = "{NS}.{kind}.desc"\npicture = GFX_evt_space_battle\nimmediate = {{ {immediate} }}\n'
        for i in range(1, 7):
            slot = f"event_target:{NS}_slot_{i}"
            valid_slot = f"has_fleet_flag = {NS}_slot_{i} is_owned_by = root {eligibility.split(' NOT =')[0]}"
            trigger = f"exists = {slot} {slot} = {{ {valid_slot} }}"
            if source:
                # Dispatching a fleet event preserves its own copy of the target
                # chain, even if the player chooses another destination later.
                effects = f"""{slot} = {{
 if = {{ limit = {{ {valid_slot} }}
  set_timed_fleet_flag = {{ flag = {NS}_active days = 180 }}
  fleet_event = {{ id = {NS}.20 days = 1 }}
 }}
}}
country_event = {{ id = {NS}.4 }}"""
            else:
                effects = f"""if = {{ limit = {{ {trigger} }}
{slot} = {{ save_event_target_as = {NS}_destination }}
{reset}
country_event = {{ id = {NS}.3 }}
}}"""
            body += option(f"{kind}.{i}", effects, trigger, f"{kind}.tt")
        body += option("next", f"country_event = {{ id = {NS}.{number} }}", f"any_owned_fleet = {{ {eligibility} }}")
        body += option("restart", f"{reset} country_event = {{ id = {NS}.{number} }}")
        body += option("back", f"{reset} country_event = {{ id = auto_qol_fleet_menu.1 }}")
        body += option("close", reset)
        text += event(number, body)
    # Refresh source list from the beginning after a selection. Active requests
    # disappear from the list; no other fleet is enrolled implicitly.
    text += event(4, f"hide_window = yes\nimmediate = {{ {reset} country_event = {{ id = {NS}.3 }} }}")
    text += f"""
# Each explicitly selected source retries for at most 180 days. No on_action,
# global scan, teleportation, ship recreation or ship deletion is used.
fleet_event = {{
 id = {NS}.20
 hide_window = yes
 is_triggered_only = yes
 immediate = {{
  if = {{
   limit = {{
    has_fleet_flag = {NS}_active
    exists = owner
    owner = {{ is_ai = no }}
    exists = event_target:{NS}_destination
    auto_qol_reassembly_worker_source = yes
    event_target:{NS}_destination = {{
     auto_qol_reassembly_owned_military = yes
     is_owned_by = root.owner
     is_controlled_by = root.owner
    }}
   }}
   set_variable = {{ which = {NS}_room value = owner.trigger:command_limit }}
   subtract_variable = {{ which = {NS}_room value = event_target:{NS}_destination.trigger:fleet_size }}
   if = {{
    limit = {{
     is_in_combat = no
     event_target:{NS}_destination = {{ is_in_combat = no }}
     solar_system = {{ is_same_value = event_target:{NS}_destination.solar_system }}
     fleet_size <= {NS}_room
    }}
    # Uses the native action, preserving ships and normal merge restrictions.
    # Exact target filter prevents nearest-fleet guesses.
    clear_orders = yes
    queue_actions = {{
     find_closest_fleet = {{
      trigger = {{
       id = "auto_qol_reassembly_exact_destination"
       is_same_value = root.event_target:{NS}_destination
      }}
      found_fleet = {{ merge_fleet = {{ target = this }} }}
     }}
    }}
    remove_fleet_flag = {NS}_active
   }}
   else = {{ fleet_event = {{ id = {NS}.20 days = 5 }} }}
   clear_variable = {NS}_room
  }}
  else = {{ remove_fleet_flag = {NS}_active }}
 }}
}}
"""
    destination = ROOT / "docs/experiments/auto_qol_reassembly_events.txt"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    build()
