"""Shared native console chrome. No event routing or gameplay effects live here.

Only build_assets needs Pillow; normal GUI/release generation uses checked-in DDS.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def panel(name, x, y, width, height, style="panel"):
    return f'''  containerWindowType = {{
   name = "{name}"
   position = {{ x = {x} y = {y} }}
   size = {{ width = {width} height = {height} }}
   background = {{ name = "background" quadTextureSprite = "GFX_auto_qol_{style}" }}
  }}
'''


def chrome(shell):
    marker = '  background = { name = "background" quadTextureSprite = "GFX_tile_large_bg" }'
    return shell.replace(marker, marker.replace('GFX_tile_large_bg', 'GFX_auto_qol_console')
                         + "\n" + panel("console_header", 12, 8, 1006, 86)
                         + panel("console_footer", 12, 600, 1006, 108))


def dashboard_panels(shell):
    marker = '  buttonType = {\n   name = "close"'
    backdrop = panel("console_context", 12, 104, 320, 486)
    backdrop += panel("console_workspace", 342, 104, 676, 486)
    return shell.replace(marker, backdrop + marker)


def build_assets(root=ROOT):
    from PIL import Image, ImageDraw
    root = Path(root)
    folder = root / "gfx/interface/auto_qol"
    folder.mkdir(parents=True, exist_ok=True)
    definitions = "# Generated by tools/console_theme.py\nspriteTypes = {\n"
    for name, fill, edge in (
        ("console", (8, 17, 21, 255), (57, 105, 102, 255)),
        ("panel", (16, 30, 34, 255), (39, 66, 68, 255)),
        ("card", (20, 39, 42, 255), (52, 95, 93, 255)),
    ):
        image = Image.new("RGBA", (32, 32), fill)
        draw = ImageDraw.Draw(image)
        draw.rectangle((0, 0, 31, 31), outline=edge)
        image.save(folder / f"{name}.dds")
        definitions += f''' corneredTileSpriteType = {{
  name = "GFX_auto_qol_{name}"
  textureFile = "gfx/interface/auto_qol/{name}.dds"
  borderSize = {{ x = 8 y = 8 }}
  effectFile = "gfx/FX/buttonstate_onlydisable.shader"
 }}
'''
    definitions += "}\n"
    (root / "interface/auto_qol_console.gfx").write_text(definitions, encoding="utf-8")


if __name__ == "__main__":
    build_assets()
